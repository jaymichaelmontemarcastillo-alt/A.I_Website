<script>
function showInquiryForm(event) {
    event.preventDefault(); // Stop anchor scroll
    const modal = document.getElementById('contactImageModal');
    if (modal) {
        modal.classList.add('show');
        document.body.style.overflow = 'hidden'; // Prevent background scroll
    }
}

function closeContactModal() {
    const modal = document.getElementById('contactImageModal');
    if (modal) {
        modal.classList.remove('show');
        document.body.style.overflow = 'auto'; // Restore scroll
    }
}

document.addEventListener('DOMContentLoaded', function() {
    const observerOptions = {
        threshold: 0.12,
        rootMargin: '0px 0px -40px 0px'
    };

    const revealObserver = new IntersectionObserver((entries, observer) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('revealed');
                observer.unobserve(entry.target);
            }
        });
    }, observerOptions);

    document.querySelectorAll('.reveal-init').forEach(element => {
        revealObserver.observe(element);
    });

    if (window.location.hash === '#inquiry-section') {
        setTimeout(() => {
            const firstNameInput = document.getElementById('firstName');
            if (firstNameInput) firstNameInput.focus();
        }, 500);
    }
});

document.getElementById('attachReference').addEventListener('change', function(e) {
    const files = e.target.files;
    const display = document.getElementById('fileNameDisplay');
    if (files.length > 0) {
        display.textContent = files.length === 1 ? files[0].name : files.length + ' files selected';
    } else {
        display.textContent = 'Logo, design brief, or inspiration — PNG, JPG, PDF';
    }
});

document.getElementById('inquiryForm').addEventListener('submit', function(e) {
    e.preventDefault();
    const btn    = document.getElementById('submitInquiryBtn');
    const status = document.getElementById('inquiryStatus');
    const formData = new FormData(this);

    btn.disabled = true;
    btn.innerHTML = '<i class="fas fa-circle-notch fa-spin"></i> Sending...';
    status.style.display = 'none';

    fetch('api/customer_site/send_inquiry.php', {
        method: 'POST',
        body: formData
    })
    .then(response => response.json())
    .then(data => {
        status.style.display = 'block';
        if (data.success) {
            status.style.color = '#4ade80';
            status.innerHTML = '<i class="fas fa-check-circle"></i> Inquiry sent! We\'ll get back to you within 1–2 business days.';
            document.getElementById('inquiryForm').reset();
            document.getElementById('fileNameDisplay').textContent = 'Logo, design brief, or inspiration — PNG, JPG, PDF';
        } else {
            status.style.color = '#f87171';
            status.innerHTML = '<i class="fas fa-exclamation-circle"></i> ' + data.message;
        }
    })
    .catch(error => {
        status.style.display = 'block';
        status.style.color = '#f87171';
        status.innerHTML = '<i class="fas fa-exclamation-circle"></i> An error occurred. Please try again.';
        console.error('Error:', error);
    })
    .finally(() => {
        btn.disabled = false;
        btn.innerHTML = '<i class="fas fa-paper-plane"></i> Send Inquiry';
    });
});
</script>

